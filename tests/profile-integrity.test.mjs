import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { localReferences, missingLocalReferences, markersValid, checkProfile } from '../scripts/check-profile.mjs';

test('collects local Markdown and HTML references, ignoring external and anchor URLs', () => {
  const body = [
    '![Hero](./assets/hero.svg)',
    '[Projects](./PROJECTS.md)',
    '<img src="./assets/hero.svg">',
    '<a href="https://github.com/Ahmed8xdev">External</a>',
    '[Jump](#contact)',
    '![Image](data:image/png;base64,AAAA)',
  ].join('\n');
  assert.deepEqual(localReferences(body), ['./assets/hero.svg', './PROJECTS.md']);
});

test('rejects unresolved file paths and repository traversal', async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'gh-profile-'));
  try {
    await fs.mkdir(path.join(root, 'assets'));
    await fs.writeFile(path.join(root, 'assets', 'hero.svg'), '<svg></svg>');
    const misses = await missingLocalReferences(root, 'README.md',
      '<img src="./assets/hero.svg"><img src="./assets/missing.svg">[escape](../../etc/passwd)');
    assert.equal(misses.length, 2);
    assert.deepEqual(misses.map(x => x.reason), ['not found', 'path escapes repository root']);
  } finally { await fs.rm(root, { recursive: true, force: true }); }
});

test('requires one ordered pair of autogenerated project markers', () => {
  const start = '<!-- AUTO-PROJECTS:START -->';
  const end = '<!-- AUTO-PROJECTS:END -->';
  assert.ok(markersValid('before ' + start + ' contents ' + end + ' after'));
  assert.ok(!markersValid(start + start + end));
  assert.ok(!markersValid(end + start));
});

test('the repository profile and all linked local assets remain valid', async () => {
  assert.deepEqual(await checkProfile(), []);
});
